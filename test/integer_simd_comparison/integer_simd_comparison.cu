extern "C" __global__ void simd_comparison(unsigned* out, const unsigned* in, unsigned count) {
    unsigned block = blockIdx.x + gridDim.x * blockIdx.y;
    unsigned i = block * blockDim.x + threadIdx.x;
    if (i >= count) return;
    in += i * 3; out += i * 48;
    unsigned a = in[0], b = in[1], c = in[2];
    out[0] = __vseteq2(a,b);
    out[1] = __vseteq4(a,b);
    out[2] = __vsetges2(a,b);
    out[3] = __vsetges4(a,b);
    out[4] = __vsetgeu2(a,b);
    out[5] = __vsetgeu4(a,b);
    out[6] = __vsetgts2(a,b);
    out[7] = __vsetgts4(a,b);
    out[8] = __vsetgtu2(a,b);
    out[9] = __vsetgtu4(a,b);
    out[10] = __vsetles2(a,b);
    out[11] = __vsetles4(a,b);
    out[12] = __vsetleu2(a,b);
    out[13] = __vsetleu4(a,b);
    out[14] = __vsetlts2(a,b);
    out[15] = __vsetlts4(a,b);
    out[16] = __vsetltu2(a,b);
    out[17] = __vsetltu4(a,b);
    out[18] = __vsetne2(a,b);
    out[19] = __vsetne4(a,b);
    out[20] = __vcmpeq2(a,b);
    out[21] = __vcmpeq4(a,b);
    out[22] = __vcmpges2(a,b);
    out[23] = __vcmpges4(a,b);
    out[24] = __vcmpgeu2(a,b);
    out[25] = __vcmpgeu4(a,b);
    out[26] = __vcmpgts2(a,b);
    out[27] = __vcmpgts4(a,b);
    out[28] = __vcmpgtu2(a,b);
    out[29] = __vcmpgtu4(a,b);
    out[30] = __vcmples2(a,b);
    out[31] = __vcmples4(a,b);
    out[32] = __vcmpleu2(a,b);
    out[33] = __vcmpleu4(a,b);
    out[34] = __vcmplts2(a,b);
    out[35] = __vcmplts4(a,b);
    out[36] = __vcmpltu2(a,b);
    out[37] = __vcmpltu4(a,b);
    out[38] = __vcmpne2(a,b);
    out[39] = __vcmpne4(a,b);
    unsigned r40;
    asm("vset2.u32.u32.eq.add %0,%1,%2,%3;" : "=r"(r40) : "r"(a), "r"(b), "r"(c));
    out[40] = r40;
    unsigned r41;
    asm("vset4.u32.u32.eq.add %0,%1,%2,%3;" : "=r"(r41) : "r"(a), "r"(b), "r"(c));
    out[41] = r41;
    unsigned r42;
    asm("vset2.u32.u32.ne.add %0,%1,%2,%3;" : "=r"(r42) : "r"(a), "r"(b), "r"(c));
    out[42] = r42;
    unsigned r43;
    asm("vset4.u32.u32.ne.add %0,%1,%2,%3;" : "=r"(r43) : "r"(a), "r"(b), "r"(c));
    out[43] = r43;
    unsigned r44;
    asm("vset2.s32.s32.lt.add %0,%1,%2,%3;" : "=r"(r44) : "r"(a), "r"(b), "r"(c));
    out[44] = r44;
    unsigned r45;
    asm("vset4.s32.s32.lt.add %0,%1,%2,%3;" : "=r"(r45) : "r"(a), "r"(b), "r"(c));
    out[45] = r45;
    unsigned r46;
    asm("vset2.u32.u32.ge.add %0,%1,%2,%3;" : "=r"(r46) : "r"(a), "r"(b), "r"(c));
    out[46] = r46;
    unsigned r47;
    asm("vset4.u32.u32.ge.add %0,%1,%2,%3;" : "=r"(r47) : "r"(a), "r"(b), "r"(c));
    out[47] = r47;
}
