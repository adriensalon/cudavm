"""Generate binary64 exp/log references using Python's correctly rounded Decimal.

No GPU or cudavm code supplies expected values. Run with Python 3.11 or newer.
Intervals enclose Decimal transcendental rounding and every base conversion;
both endpoints must round to the same binary64 value. Exact exp2 integer ties
are evaluated as rational powers of two instead of through ln(2).
"""
from decimal import Decimal as D, localcontext, ROUND_FLOOR, ROUND_CEILING
from pathlib import Path
import struct

SIGN = 1 << 63
INF = 0x7ff0000000000000
NAN = 0x7ff8000000000000

def word(value):
    return struct.unpack('<Q', struct.pack('<d', value))[0]

def value(bits):
    return struct.unpack('<d', struct.pack('<Q', bits))[0]

def unary_interval(x, method):
    y = getattr(x, method)()
    return y.next_minus(), y.next_plus()

def multiply(a, b):
    with localcontext() as ctx:
        ctx.rounding = ROUND_FLOOR
        low = min(x * y for x in a for y in b)
        ctx.rounding = ROUND_CEILING
        high = max(x * y for x in a for y in b)
    return low, high

def divide(a, b):
    assert b[0] > 0
    with localcontext() as ctx:
        ctx.rounding = ROUND_FLOOR
        low = min(x / y for x in a for y in b)
        ctx.rounding = ROUND_CEILING
        high = max(x / y for x in a for y in b)
    return low, high

def rounded(interval):
    a, b = (word(float(x)) for x in interval)
    assert a == b, f'ambiguous binary64 rounding: {interval}'
    return a

def expected(bits, logarithm):
    x = D.from_float(value(bits))
    if x.is_nan():
        return (NAN,) * 3
    if logarithm:
        if x.is_zero():
            return (SIGN | INF,) * 3
        if x.is_signed():
            return (NAN,) * 3
        if x.is_infinite():
            return (INF,) * 3
        if x == 1:
            return (0,) * 3
        ln = unary_interval(x, 'ln')
        return rounded(ln), rounded(divide(ln, LN2)), rounded(divide(ln, LN10))
    if x.is_infinite() or abs(x) > 2048:
        return (0 if x.is_signed() else INF,) * 3
    result = [rounded(unary_interval(x, 'exp'))]
    for base, logarithm_base in ((2, LN2), (10, LN10)):
        if x == x.to_integral_value():
            # Exact base**integer as a rational, including underflow midpoints.
            exponent = int(x)
            if base == 2:
                numerator, denominator = (2**exponent, 1) if exponent >= 0 else (1, 2**-exponent)
                try:
                    result.append(word(numerator / denominator))
                except OverflowError:
                    result.append(INF)
            else:
                result.append(word(float(D(f'1e{exponent}'))))
            continue
        lower, upper = multiply((x, x), logarithm_base)
        interval = unary_interval(lower, 'exp')[0], unary_interval(upper, 'exp')[1]
        result.append(rounded(interval))
    return tuple(result)

def inputs(logarithm):
    words = {0, SIGN, INF, INF | SIGN, NAN, NAN | SIGN, INF | 1, SIGN | INF | 1}
    for exponent in range(2047):
        for fraction in (0, 1, (1 << 51) - 1, (1 << 52) - 1):
            bits = exponent << 52 | fraction
            words.add(bits)
            if not logarithm:
                words.add(bits | SIGN)
    # Independent fixed-width LCG, including arbitrary significands/subnormals.
    state = 0xd1b54a32d192ed03
    for _ in range(1024):
        state = (state * 6364136223846793005 + 1442695040888963407) & (SIGN - 1)
        words.add(state)
    if logarithm:
        for center in (1, 0x0010000000000000, word(0.5), word(1.0), word(2.0), word(10.0)):
            for step in range(-32, 33):
                if center + step >= 0:
                    words.add(center + step)
        for bits in list(words):
            words.add(bits | SIGN)
    else:
        # Dyadic dense finite range and neighbors of each function's transitions.
        for integer in range(-8800, 8201, 7):
            words.add(word(integer / 8))
        for center in (-1075.0, -1074.0, -1022.0, 1024.0, -745.1332191019411,
                       -708.3964185322641, 709.782712893384, -323.60724533877976,
                       -307.6526555685888, 308.25471555991675):
            for step in range(-32, 33):
                words.add(word(center) + step)
    return sorted(words)

def generate():
    output = ['// Generated by generate_reference.py; independent Decimal interval references.']
    for logarithm, name in ((False, 'exponential'), (True, 'logarithmic')):
        output.append(f'constexpr uint64_t double_{name}_reference[][4]{{')
        for bits in inputs(logarithm):
            row = (bits,) + expected(bits, logarithm)
            output.append('    {' + ', '.join(f'0x{x:016x}ull' for x in row) + '},')
        output.append('};')
        print(name, 'generated', flush=True)
    Path(__file__).with_name('reference.hpp').write_text('\n'.join(output) + '\n', encoding='ascii')

if __name__ == '__main__':
    with localcontext() as context:
        context.prec = 160
        # Python Decimal ln/exp are correctly rounded in ROUND_HALF_EVEN.
        LN2, LN10 = unary_interval(D(2), 'ln'), unary_interval(D(10), 'ln')
        generate()
